const toggle = document.querySelector("#language-toggle");
const savedLanguage = localStorage.getItem("portfolio-language");
let currentLanguage = savedLanguage === "en" ? "en" : "tr";

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key]) element.textContent = translations[language][key];
  });
  toggle.textContent = language === "tr" ? "EN" : "TR";
  toggle.setAttribute("aria-label", language === "tr" ? "Switch to English" : "Türkçeye geç");
  document.title = language === "tr" ? "Atakan | Kişisel Portföy" : "Atakan | Personal Portfolio";
  localStorage.setItem("portfolio-language", language);
}

toggle.addEventListener("click", () => setLanguage(currentLanguage === "tr" ? "en" : "tr"));
document.querySelector("#year").textContent = new Date().getFullYear();
