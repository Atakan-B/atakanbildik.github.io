// Progressive enhancement: gentle cursor spotlight, reveal-on-scroll,
// card highlight/tilt, and a top reading-progress indicator.
(() => {
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const coarsePointer = window.matchMedia("(pointer: coarse)").matches;
  const progress = document.querySelector(".scroll-progress");
  const root = document.documentElement;

  if (!reduceMotion) {
    document.body.classList.add("js-motion");

    const revealTargets = document.querySelectorAll(
      ".hero-copy > *, .hero-card, .section-heading, .about-grid > *, .skill-card, .project-card, .approach-grid > div, .contact-section > *"
    );

    revealTargets.forEach((element, index) => {
      element.setAttribute("data-reveal", "");
      if (element.classList.contains("skill-card") || element.classList.contains("project-card")) {
        element.style.setProperty("--reveal-delay", `${(index % 3) * 75}ms`);
      }
    });

    if ("IntersectionObserver" in window) {
      const observer = new IntersectionObserver((entries, obs) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-visible");
            obs.unobserve(entry.target);
          }
        });
      }, { threshold: 0.12, rootMargin: "0px 0px -35px 0px" });
      revealTargets.forEach((element) => observer.observe(element));
    } else {
      revealTargets.forEach((element) => element.classList.add("is-visible"));
    }

    if (!coarsePointer) {
      let frame = null;
      window.addEventListener("pointermove", (event) => {
        if (frame) cancelAnimationFrame(frame);
        frame = requestAnimationFrame(() => {
          root.style.setProperty("--pointer-x", `${event.clientX}px`);
          root.style.setProperty("--pointer-y", `${event.clientY}px`);
          document.body.classList.add("pointer-active");
        });
      }, { passive: true });

      document.addEventListener("pointerleave", () => {
        document.body.classList.remove("pointer-active");
      });

      document.querySelectorAll(".skill-card, .project-card").forEach((card) => {
        card.addEventListener("pointermove", (event) => {
          const rect = card.getBoundingClientRect();
          card.style.setProperty("--card-x", `${event.clientX - rect.left}px`);
          card.style.setProperty("--card-y", `${event.clientY - rect.top}px`);
        }, { passive: true });
      });
    }
  }

  const updateProgress = () => {
    if (!progress) return;
    const scrollable = document.documentElement.scrollHeight - window.innerHeight;
    const amount = scrollable > 0 ? (window.scrollY / scrollable) * 100 : 0;
    progress.style.width = `${Math.min(100, Math.max(0, amount))}%`;
  };
  window.addEventListener("scroll", updateProgress, { passive: true });
  window.addEventListener("resize", updateProgress);
  updateProgress();
})();

(() => {
  const canvas = document.getElementById("particle-network");
  if (!canvas) return;

  const ctx = canvas.getContext("2d");
  if (!ctx) return;

  const reducedMotion = window.matchMedia(
    "(prefers-reduced-motion: reduce)"
  );

  if (reducedMotion.matches) return;

  let width = 0;
  let height = 0;
  let particles = [];
  let animationId;

  const mouse = {
    x: -1000,
    y: -1000,
    radius: 130
  };

  function resize() {
    const dpr = Math.min(window.devicePixelRatio || 1, 2);

    width = window.innerWidth;
    height = window.innerHeight;

    canvas.width = Math.floor(width * dpr);
    canvas.height = Math.floor(height * dpr);
    canvas.style.width = `${width}px`;
    canvas.style.height = `${height}px`;

    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

    const count = Math.min(
      110,
      Math.max(35, Math.floor((width * height) / 14000))
    );

    particles = Array.from({ length: count }, () => ({
      x: Math.random() * width,
      y: Math.random() * height,
      vx: (Math.random() - 0.5) * 0.45,
      vy: (Math.random() - 0.5) * 0.45,
      radius: Math.random() * 1.5 + 0.7
    }));
  }

  function draw() {
    ctx.clearRect(0, 0, width, height);

    for (const p of particles) {
      p.x += p.vx;
      p.y += p.vy;

      if (p.x < 0 || p.x > width) p.vx *= -1;
      if (p.y < 0 || p.y > height) p.vy *= -1;

      const dx = mouse.x - p.x;
      const dy = mouse.y - p.y;
      const distance = Math.hypot(dx, dy);

      if (distance < mouse.radius && distance > 0) {
        p.x -= (dx / distance) * 0.18;
        p.y -= (dy / distance) * 0.18;
      }

      ctx.beginPath();
      ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
      ctx.fillStyle = "rgba(125, 211, 199, 0.8)";
      ctx.fill();
    }

    for (let i = 0; i < particles.length; i++) {
      for (let j = i + 1; j < particles.length; j++) {
        const a = particles[i];
        const b = particles[j];
        const distance = Math.hypot(a.x - b.x, a.y - b.y);

        if (distance < 115) {
          const opacity = (1 - distance / 115) * 0.28;

          ctx.beginPath();
          ctx.moveTo(a.x, a.y);
          ctx.lineTo(b.x, b.y);
          ctx.strokeStyle = `rgba(125, 211, 199, ${opacity})`;
          ctx.lineWidth = 0.7;
          ctx.stroke();
        }
      }
    }

    animationId = requestAnimationFrame(draw);
  }

  window.addEventListener("resize", resize);

  window.addEventListener("pointermove", (event) => {
    mouse.x = event.clientX;
    mouse.y = event.clientY;
  });

  window.addEventListener("pointerleave", () => {
    mouse.x = -1000;
    mouse.y = -1000;
  });

  resize();
  draw();
})();
